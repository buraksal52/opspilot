import uuid
from dataclasses import dataclass
from datetime import datetime
from enum import StrEnum


class DatasetStatus(StrEnum):
    PROCESSING = "PROCESSING"
    READY = "READY"
    FAILED = "FAILED"


@dataclass(frozen=True, slots=True)
class ColumnDefinition:
    """One entry of Dataset.schema_definition (DATA_MODEL.md §8).

    `display_name` is untrusted (taken from the CSV header) and is presentation
    only. `physical_name` is application-generated (ADR-017) and is the only
    name ever used to build SQL/DDL against the analytics table.
    """

    display_name: str
    physical_name: str
    type: str
    nullable: bool


@dataclass(frozen=True, slots=True)
class Dataset:
    id: uuid.UUID
    workspace_id: uuid.UUID
    data_source_id: uuid.UUID
    name: str
    description: str | None
    # ADR-017: generated by the application from Dataset.id — never derived
    # from the uploaded filename or CSV header text.
    physical_table_name: str
    row_count: int
    column_count: int
    schema_definition: list[ColumnDefinition]
    profile_statistics: dict
    status: DatasetStatus
    created_at: datetime
    updated_at: datetime
